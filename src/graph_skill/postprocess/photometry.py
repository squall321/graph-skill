def gamut_area_ratio(tri, ref):
    """삼각형 면적비 (커버리지 % 근사용, 단순 면적비)."""
    def area(t):
        (x1, y1), (x2, y2), (x3, y3) = t
        return abs((x2 - x1) * (y3 - y1) - (x3 - x1) * (y2 - y1)) / 2.0
    return area(tri) / (area(ref) or 1e-12)


# ── IEC 61260 1/3 옥타브 공칭 중심주파수 (공개 표준 상수) ───────────────────
THIRD_OCTAVE_FC = [20, 25, 31.5, 40, 50, 63, 80, 100, 125, 160, 200, 250, 315, 400,
                   500, 630, 800, 1000, 1250, 1600, 2000, 2500, 3150, 4000, 5000,
                   6300, 8000, 10000, 12500, 16000, 20000]


def band_edges(fc):
    """1/3 옥타브 밴드 상/하한 (base-2)."""
    k = 2 ** (1 / 6)
    return fc / k, fc * k


def spectrum_to_third_octave(freqs, levels_db):
    """협대역 스펙트럼(dB) → 1/3 옥타브 밴드 레벨(에너지 합산).
    반환: [(fc, level_dB)] — 입력 범위에 걸친 밴드만."""
    out = []
    for fc in THIRD_OCTAVE_FC:
        f_lo, f_hi = band_edges(fc)
        acc = 0.0
        n = 0
        for f, lv in zip(freqs, levels_db):
            if f_lo <= f < f_hi:
                acc += 10 ** (lv / 10.0)
                n += 1
        if n:
            out.append((fc, 10 * math.log10(acc)))
    return out
